const dict: Record<Lang, Record<UIKey, string>> = { en, bg };

export function t(lang: Lang, key: UIKey, vars: Record<string, string | number> = {}): string {
  const s = dict[lang][key] ?? dict.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

/** Detect the language from a URL path: /bg/... is Bulgarian. */
export function langFromPath(pathname: string): Lang {
  return pathname === '/bg' || pathname.startsWith('/bg/') ? 'bg' : 'en';
}

/** Prefix an English path for a language: ('/001-x/', 'bg') -> '/bg/001-x/' */
export function localize(path: string, lang: Lang): string {
  const clean = stripLang(path);
  return lang === 'en' ? clean : `/bg${clean}`;
}

export function stripLang(path: string): string {
  return path.replace(/^\/bg(?=\/|$)/, '') || '/';
}

export function formatMinutes(lang: Lang, n: number): string {
  if (n < 60) return t(lang, 'minutes', { n });
  const h = Math.floor(n / 60);
  const m = n % 60;
  return m ? t(lang, 'hours', { h, m }) : t(lang, 'hoursOnly', { h });
}

export function statusText(lang: Lang, status: string): string {
  if (!status) return '';
  const key = `status.${status.toUpperCase()}` as UIKey;
  if (key in en) return t(lang, key);
  const s = status.toLowerCase();
  return s.charAt(0).toUpperCase() + s.slice(1);
}
