// Game content (v2 Phase 2): content-meta/games/*.yaml → src/data/games.json.
//
//   node scripts/games.mjs check            validate and build (runs before every build)
//   node scripts/games.mjs review           write docs/games-review.md for Semir to skim
//   node scripts/games.mjs approve all      mark every proposed round approved
//   node scripts/games.mjs approve id1 id2  …or only some
//
// Only approved rounds are played on the live site; `npm run dev` plays proposed ones too.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { parse, parseDocument } from 'yaml';
import { sectionIndex } from './knowledge.mjs';

const ROOT = new URL('../', import.meta.url);
const FILE = new URL('content-meta/games/fallacies.yaml', ROOT);

export function validateFallacies(data, index) {
  const errors = [];
  const fallacies = data?.fallacies ?? [], rounds = data?.rounds ?? [];
  const ids = new Set();
  for (const f of fallacies) {
    const at = `fallacy “${f?.id}”`;
    if (!f?.id || ids.has(f.id)) errors.push(`${at}: missing or duplicate id`);
    ids.add(f?.id);
    for (const k of ['name', 'bg', 'explanation', 'explanationBg']) if (!f?.[k]) errors.push(`${at}: needs ${k}`);
    if (!index.ids.has(f?.section)) errors.push(`${at}: section “${f?.section}” doesn't exist`);
  }
  const rids = new Set();
  for (const r of rounds) {
    const at = `round “${r?.id}”`;
    if (!r?.id || rids.has(r.id)) errors.push(`${at}: missing or duplicate id`);
    rids.add(r?.id);
    if (!r?.argument || !r?.bg) errors.push(`${at}: needs argument and bg`);
    if (!ids.has(r?.answer)) errors.push(`${at}: answer “${r?.answer}” isn't a listed fallacy`);
    if (!Array.isArray(r?.options) || r.options.length < 2 || r.options.length > 3) errors.push(`${at}: needs 2–3 other options`);
    for (const o of r?.options ?? []) {
      if (!ids.has(o)) errors.push(`${at}: option “${o}” isn't a listed fallacy`);
      if (o === r.answer) errors.push(`${at}: the answer is also listed as a wrong option`);
    }
    if (!['proposed', 'approved'].includes(r?.status)) errors.push(`${at}: status must be proposed or approved`);
    const src = String(r?.source ?? '');
    if (!(src === 'drafted' || (src.startsWith('book: ') && index.ids.has(src.slice(6))))) errors.push(`${at}: source must be "drafted" or "book: NNN/section"`);
  }
  return errors;
}

function compile(data, index) {
  return {
    _generated: 'by scripts/games.mjs from content-meta/games/*.yaml. Edit those, not this.',
    fallacies: data.fallacies.map((f) => ({ id: f.id, name: { en: f.name, bg: f.bg }, explanation: { en: f.explanation, bg: f.explanationBg },
      url: index.ids.get(f.section) })),
    rounds: data.rounds.map((r) => ({ id: r.id, argument: { en: r.argument, bg: r.bg }, answer: r.answer, options: r.options,
      fromBook: r.source !== 'drafted', status: r.status })),
  };
}

function review(data) {
  const name = Object.fromEntries(data.fallacies.map((f) => [f.id, f.name]));
  const out = ['# Game content review', '',
    '*GENERATED by `npm run games review`. Edit `content-meta/games/fallacies.yaml`, not this page.*', '',
    'Fallacy Detective rounds. “Book” rounds are the book\'s own examples from Chapter 002; “drafted” rounds were written',
    'for the game and are fictional. Fix or delete anything in the YAML (or tell Claude), then `npm run games approve all`.', ''];
  for (const kind of ['book', 'drafted']) {
    const list = data.rounds.filter((r) => (r.source === 'drafted') === (kind === 'drafted'));
    out.push(`## ${kind === 'book' ? 'From the book' : 'Drafted for the game'} (${list.length})`, '');
    for (const r of list) {
      out.push(`- ${r.status === 'approved' ? '✅' : '⬜'} **${r.id}**: ${r.argument}<br>*${r.bg}*<br>Answer: **${name[r.answer]}** · other choices: ${r.options.map((o) => name[o]).join(', ')}`);
    }
    out.push('');
  }
  mkdirSync(new URL('docs/', ROOT), { recursive: true });
  writeFileSync(new URL('docs/games-review.md', ROOT), out.join('\n'));
}

if (import.meta.main) {
  const [cmd = 'check', ...args] = process.argv.slice(2);
  const index = sectionIndex();
  const data = existsSync(FILE) ? parse(readFileSync(FILE, 'utf8')) : { fallacies: [], rounds: [] };
  if (cmd === 'check') {
    const errors = validateFallacies(data, index);
    if (errors.length) { console.error(`Game content has ${errors.length} problem(s):`); errors.forEach((e) => console.error(`  ✗ ${e}`)); process.exit(1); }
    writeFileSync(new URL('src/data/games.json', ROOT), JSON.stringify(compile(data, index), null, 2) + '\n');
    const ok = data.rounds.filter((r) => r.status === 'approved').length;
    console.log(`Game content OK: ${data.fallacies.length} fallacies, ${data.rounds.length} rounds (${ok} approved).`);
  } else if (cmd === 'review') {
    review(data);
    console.log('Wrote docs/games-review.md.');
  } else if (cmd === 'approve') {
    const doc = parseDocument(readFileSync(FILE, 'utf8'));
    let n = 0;
    for (const item of doc.get('rounds').items) {
      if ((args.includes('all') || args.includes(item.get('id'))) && item.get('status') === 'proposed') { item.set('status', 'approved'); n++; }
    }
    writeFileSync(FILE, doc.toString({ lineWidth: 0 }));
    console.log(`Approved ${n} rounds.`);
  } else {
    console.error('Use check, review or approve.'); process.exit(1);
  }
}
